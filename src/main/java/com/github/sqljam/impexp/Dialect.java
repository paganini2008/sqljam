    /**
     * Converts a value of the source column to a value which can be bound to the target column of this database
     *
     * @param sourceDataType jdbc type of source column
     * @param sourceTypeName type name of source column
     * @param columnSize     size of source column
     */
    public Object getJdbcValue(Object value, int sourceDataType, String sourceTypeName, int columnSize) {
        if (value == null) {
            return null;
        }
        if (value instanceof CharSequence && isTemporalType(sourceDataType)) {
            // Dates stored as text (SQLite)
            value = parseTemporal(value.toString(), sourceDataType);
        }
        if (value instanceof Number && (sourceDataType == Types.BOOLEAN
                || (sourceDataType == Types.BIT && columnSize <= 1))) {
            value = ((Number) value).intValue() != 0;
        }
        if (isCrossDatabase()) {
            if (value instanceof CharSequence && "timetz".equalsIgnoreCase(sourceTypeName)) {
                String text = value.toString().replaceAll("([+-]\\d{2})$", "$1:00");
                value = java.time.OffsetTime.parse(text).toLocalTime();
            } else if (sourceDataType == Types.BIT && columnSize > 1) {
                // Bit strings are migrated as integers
                value = toLong(value);
            } else if (value instanceof Object[]) {
                value = Arrays.deepToString((Object[]) value);
            } else if (value instanceof java.time.OffsetTime) {
                value = ((java.time.OffsetTime) value).toLocalTime();
            } else if (value instanceof OffsetDateTime) {
                // Instant in local time zone
                value = ((OffsetDateTime) value).atZoneSameInstant(java.time.ZoneId.systemDefault())
                        .toLocalDateTime();
            }
            // Fractional seconds are truncated, rounding may overflow (e.g. 9999-12-31 23:59:59.9999999)
            if (value instanceof LocalDateTime) {
                value = truncateNanos((LocalDateTime) value);
            } else if (value instanceof LocalTime) {
                value = truncateNanos((LocalTime) value);
            }
        }
        return getJdbcValue(value);
    }

