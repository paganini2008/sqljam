    protected static String formatTimestamp(LocalDateTime value) {
        String text = value.format(TIMESTAMP_FORMATTER);
        if (value.getNano() > 0) {
            text += "." + StringUtils.stripEnd(String.format("%09d", value.getNano()), "0");
        }
        return text;
    }

    protected static String formatTime(LocalTime value) {
        String text = value.format(TIME_FORMATTER);
        if (value.getNano() > 0) {
            text += "." + StringUtils.stripEnd(String.format("%09d", value.getNano()), "0");
        }
        return text;
    }

    protected static String toHexString(byte[] bytes) {
        StringBuilder hex = new StringBuilder(bytes.length * 2);
        for (byte b : bytes) {
            hex.append(Character.forDigit((b >> 4) & 0xF, 16)).append(Character.forDigit(b & 0xF, 16));
        }
        return hex.toString().toUpperCase(Locale.ENGLISH);
    }

    public String getStringValue(String catalog, String schema, String tableName, String columnName, Object columnValue) {
        if (columnValue == null) {
            return "NULL";
        }
        if (columnValue instanceof Number) {
            if (columnValue instanceof BigDecimal) {
                return ((BigDecimal) columnValue).toPlainString();
            } else if (columnValue instanceof Double || columnValue instanceof Float) {
                // Scientific notation keeps literals short, e.g. -1.0E100
                double value = ((Number) columnValue).doubleValue();
                if (Double.isNaN(value) || Double.isInfinite(value)) {
                    return "NULL";
                }
                return columnValue.toString();
            }
            return columnValue.toString();
        } else if (columnValue instanceof Character) {
            return getStringLiteral(String.valueOf((Character) columnValue));
        } else if (columnValue instanceof CharSequence) {
            return getStringLiteral(columnValue.toString());
        } else if (columnValue instanceof Boolean) {
            return getBooleanLiteral((Boolean) columnValue);
        } else if (columnValue instanceof byte[]) {
            return getBinaryLiteral((byte[]) columnValue);
        } else if (columnValue instanceof Timestamp) {
            return getTimestampLiteral(((Timestamp) columnValue).toLocalDateTime());
        } else if (columnValue instanceof java.sql.Date) {
            return getDateLiteral(((java.sql.Date) columnValue).toLocalDate());
        } else if (columnValue instanceof java.sql.Time) {
            return getTimeLiteral(((java.sql.Time) columnValue).toLocalTime());
        } else if (columnValue instanceof java.util.Date) {
            return getTimestampLiteral(new Timestamp(((java.util.Date) columnValue).getTime()).toLocalDateTime());
        } else if (columnValue instanceof LocalDateTime) {
            return getTimestampLiteral((LocalDateTime) columnValue);
        } else if (columnValue instanceof LocalDate) {
            return getDateLiteral((LocalDate) columnValue);
        } else if (columnValue instanceof LocalTime) {
            return getTimeLiteral((LocalTime) columnValue);
        } else if (columnValue instanceof OffsetDateTime) {
            return getTimestampWithTimeZoneLiteral((OffsetDateTime) columnValue);
        } else if (columnValue instanceof Object[]) {
            return getArrayLiteral(catalog, schema, tableName, columnName, (Object[]) columnValue);
        } else if (columnValue instanceof java.time.OffsetTime) {
            java.time.OffsetTime time = (java.time.OffsetTime) columnValue;
            return getStringLiteral(formatTime(time.toLocalTime()) + time.getOffset());
        } else if (columnValue instanceof ZonedDateTime) {
            return getTimestampLiteral(((ZonedDateTime) columnValue).toLocalDateTime());
        }
        return getStringLiteral(columnValue.toString());
    }

