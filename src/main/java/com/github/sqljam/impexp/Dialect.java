    /**
     * Resolves column type of this dialect from jdbc metadata of the source column
     */
    public String getColumnTypeName(int dataType, String typeName, int columnSize, int columnScale) {
        if (isCrossDatabase() && StringUtils.startsWithIgnoreCase(typeName, "interval")) {
            // Interval literals are not compatible across databases
            dataType = Types.VARCHAR;
            columnSize = 100;
            typeName = "varchar";
        }
        if (isCrossDatabase() && getSourceDbType() == DbType.SQLSERVER && dataType == Types.TINYINT) {
            // tinyint of SQL Server is unsigned (0-255)
            dataType = Types.SMALLINT;
        }
        if (isCrossDatabase() && StringUtils.containsIgnoreCase(typeName, "unsigned")) {
            // Unsigned integers of MySQL are widened to keep the value range
            switch (dataType) {
                case Types.TINYINT:
                    dataType = Types.SMALLINT;
                    break;
                case Types.SMALLINT:
                    dataType = Types.INTEGER;
                    break;
                case Types.INTEGER:
                    dataType = Types.BIGINT;
                    break;
                case Types.BIGINT:
                    dataType = Types.NUMERIC;
                    columnSize = 20;
                    columnScale = 0;
                    break;
                default:
                    break;
            }
            if (StringUtils.startsWithIgnoreCase(typeName, "mediumint")) {
                dataType = Types.INTEGER;
            }
            typeName = typeName.replaceAll("(?i)\\s*unsigned", "").replaceAll("(?i)^(tiny|small|medium|big)?int.*",
                    "");
        }
        if (!isCrossDatabase() && StringUtils.isNotBlank(typeName)) {
            String nativeTypeName = getNativeTypeName(dataType, typeName, columnSize, columnScale);
            if (nativeTypeName != null) {
                return nativeTypeName;
            }
        }
        switch (dataType) {
            case -8:
            case -103:
            case -104:
            case -145:
                columnSize = Math.max(columnSize, 64);
                break;
            default:
                break;
        }
        dataType = resolveDataType(dataType, typeName);
        if ("sql_variant".equalsIgnoreCase(typeName)) {
            columnSize = 4000;
        }
        String special = getSpecialTypeName(dataType, StringUtils.defaultString(typeName).toLowerCase(Locale.ENGLISH),
                columnSize, columnScale);
        if (special != null) {
            return special;
        }
        if (dataType == Types.NUMERIC || dataType == Types.DECIMAL) {
            if (columnScale < 0) {
                columnScale = 0;
            }
            if (columnSize <= 0 || columnSize > getMaxNumericPrecision()) {
                return getUnboundedNumericTypeName();
            }
            if (columnScale == 0 && getSourceDbType() == DbType.ORACLE && columnSize <= 19) {
                return columnSize <= 4 ? getTypeName(Types.SMALLINT)
                        : columnSize <= 9 ? getTypeName(Types.INTEGER) : getTypeName(Types.BIGINT);
            }
        }
        if (dataType == Types.ARRAY || dataType == Types.STRUCT || dataType == Types.DISTINCT
                || dataType == Types.REF) {
            dataType = Types.LONGVARCHAR;
            columnSize = Integer.MAX_VALUE;
        }
        try {
            return getTypeName(dataType, columnSize, columnSize, columnScale);
        } catch (TypeMappingException e) {
            // Unknown types are migrated as text
            return getTypeName(Types.LONGVARCHAR, Integer.MAX_VALUE, Integer.MAX_VALUE, 0);
        }
    }

    /**
     * Standard jdbc type of a column by its type code and type name, vendor specific codes are ambiguous
     */
    public static int resolveDataType(int dataType, String typeName) {
        String lowerTypeName = StringUtils.defaultString(typeName).toLowerCase(Locale.ENGLISH);
        switch (lowerTypeName) {
            case "sql_variant":
            case "hierarchyid":
                return lowerTypeName.equals("sql_variant") ? Types.VARCHAR : Types.VARBINARY;
            case "datetime":
            case "smalldatetime":
                return dataType == Types.DATE || dataType == Types.TIMESTAMP ? dataType : Types.TIMESTAMP;
            case "money":
            case "smallmoney":
                return Types.DECIMAL;
            case "geography":
            case "geometry":
                return Types.LONGVARBINARY;
            default:
                return normalizeDataType(dataType);
        }
    }

    /**
     * Converts vendor specific jdbc type codes to standard ones
     */
    public static int normalizeDataType(int dataType) {
        switch (dataType) {
            case -101: // oracle TIMESTAMP WITH TIME ZONE
            case -155: // sql server DATETIMEOFFSET
                return Types.TIMESTAMP_WITH_TIMEZONE;
            case -102: // oracle TIMESTAMP WITH LOCAL TIME ZONE
            case -151: // sql server DATETIME
            case -150: // sql server SMALLDATETIME
                return Types.TIMESTAMP;
            case 100: // oracle BINARY_FLOAT
                return Types.REAL;
            case 101: // oracle BINARY_DOUBLE
                return Types.DOUBLE;
            case -148: // sql server MONEY
            case -146: // sql server SMALLMONEY
                return Types.DECIMAL;
            case -8: // ROWID
            case -103: // oracle INTERVAL YEAR TO MONTH
            case -104: // oracle INTERVAL DAY TO SECOND
            case -145: // sql server GUID
            case -156: // sql server SQL_VARIANT
                return Types.VARCHAR;
            case -157: // sql server GEOMETRY
            case -158: // sql server GEOGRAPHY
                return Types.LONGVARBINARY;
            default:
                return dataType;
        }
    }

