    public boolean isReservedWord(String word) {
        return word != null && reservedWords.contains(word.toLowerCase(Locale.ENGLISH));
    }

    /**
     * Converts identifier case of a source name to this database's convention
     */
    public String foldIdentifier(String name) {
        if (StringUtils.isBlank(name)) {
            return name;
        }
        switch (identifierCase) {
            case LOWER:
                return name.toLowerCase(Locale.ENGLISH);
            case UPPER:
                return name.toUpperCase(Locale.ENGLISH);
            case KEEP:
                return name;
            default:
                if (!isCrossDatabase()) {
                    return name;
                }
                boolean allLower = name.equals(name.toLowerCase(Locale.ENGLISH));
                boolean allUpper = name.equals(name.toUpperCase(Locale.ENGLISH));
                if (!allLower && !allUpper) {
                    return name;
                }
                return getStoredIdentifierCase() == IdentifierCase.UPPER ? name.toUpperCase(Locale.ENGLISH)
                        : name.toLowerCase(Locale.ENGLISH);
        }
    }

    public boolean isQuoteRequired(String name) {
        if (!SIMPLE_IDENTIFIER.matcher(name).matches() || isReservedWord(name)) {
            return true;
        }
        IdentifierCase stored = getStoredIdentifierCase();
        if (stored == IdentifierCase.UPPER) {
            return !name.equals(name.toUpperCase(Locale.ENGLISH));
        } else if (stored == IdentifierCase.LOWER) {
            return !name.equals(name.toLowerCase(Locale.ENGLISH));
        }
        return false;
    }

    public String quoteIdentifier(String name) {
        if (StringUtils.isBlank(name) || !isQuoteRequired(name)) {
            return name;
        }
        return getOpenQuote() + name.replace(getCloseQuote(), getCloseQuote() + getCloseQuote()) + getCloseQuote();
    }

    /**
     * Folds and quotes an identifier used in generated DDL/DML
     */
    public String getIdentifier(String name) {
        return quoteIdentifier(foldIdentifier(name));
    }

    public String getIdentifiers(String[] names) {
        return Arrays.stream(names).map(this::getIdentifier).collect(Collectors.joining(","));
    }

    /**
     * Comma separated column names (as passed by metadata) to quoted list
     */
    public String getIdentifiers(String names) {
        return getIdentifiers(Arrays.stream(names.split(",")).map(String::trim).toArray(String[]::new));
    }

    /**
     * Table reference used in generated DDL/DML (target side)
     */
    public String getQualifiedTableName(String catalog, String schema, String tableName) {
        String qualifier = getQualifier(targetCatalogName, getTargetSchemaName(schema));
        return StringUtils.isNotBlank(qualifier) ? qualifier + "." + getIdentifier(tableName) : getIdentifier(tableName);
    }

    protected String getQualifier(String catalog, String schema) {
        return StringUtils.isNotBlank(schema) ? getIdentifier(schema) : null;
    }

    /**
     * Fully qualified table reference used for reading from this database (source side)
     */
    public String getSourceTableName(String catalog, String schema, String tableName) {
        StringBuilder ref = new StringBuilder();
        if (StringUtils.isNotBlank(schema)) {
            ref.append(quoteIdentifier(schema)).append(".");
        }
        return ref.append(quoteIdentifier(tableName)).toString();
    }

    /**
     * Truncates the name to the maximum identifier length, keeping it unique with a hash suffix
     */
    public String getLimitedIdentifier(String name) {
        int max = getMaxIdentifierLength();
        if (name == null || name.length() <= max) {
            return name;
        }
        String hash = Integer.toHexString(name.hashCode() & 0x7fffffff);
        return name.substring(0, max - hash.length() - 1) + "_" + hash;
    }

