    public String getCreateForeignKeyStatement(String catalog, String schema, String tableName, String fkName,
                                               String[] columnNames, String refTableName, String[] refColumnNames,
                                               String updateRule, String deleteRule) {
        StringBuilder sql = new StringBuilder();
        sql.append(String.format("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s)",
                getQualifiedTableName(catalog, schema, tableName), quoteIdentifier(getLimitedIdentifier(foldIdentifier(fkName))), getIdentifiers(columnNames),
                getQualifiedTableName(catalog, schema, refTableName), getIdentifiers(refColumnNames)));
        if (StringUtils.isNotBlank(deleteRule)) {
            sql.append(" ON DELETE ").append(deleteRule);
        }
        if (StringUtils.isNotBlank(updateRule) && isOnUpdateRuleSupported()) {
            sql.append(" ON UPDATE ").append(updateRule);
        }
        return sql.toString();
    }

