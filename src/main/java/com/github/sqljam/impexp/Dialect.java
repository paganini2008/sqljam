    /**
     * Translates the default value expression of the source column to this dialect. Expressions which can not be
     * translated are discarded.
     */
    public String getDefaultValue(int dataType, String typeName, String defaultValue) {
        if (StringUtils.isBlank(defaultValue)) {
            return null;
        }
        defaultValue = defaultValue.trim();
        if (!isCrossDatabase()) {
            return defaultValue;
        }
        String expr = defaultValue.replaceAll("(?is)\\s+on\\s+update\\s+.*$", "");
        boolean changed = true;
        while (changed) {
            changed = false;
            if (expr.startsWith("(") && expr.endsWith(")") && isWrapped(expr)) {
                expr = expr.substring(1, expr.length() - 1).trim();
                changed = true;
            }
            Matcher castMatcher = PG_CAST.matcher(expr);
            if (castMatcher.matches()) {
                expr = castMatcher.group(1).trim();
                changed = true;
            }
        }
        if ("null".equalsIgnoreCase(expr)) {
            return null;
        }
        // BIT(n > 1) of MySQL is a bit string, other BIT columns are booleans
        boolean booleanColumn = dataType == Types.BOOLEAN || "bool".equalsIgnoreCase(typeName)
                || (dataType == Types.BIT && !StringUtils.defaultString(typeName).toLowerCase(Locale.ENGLISH)
                .matches("bit\\((?!1\\))\\d+\\)"));
        if ("true".equalsIgnoreCase(expr) || "b'1'".equalsIgnoreCase(expr)) {
            return getBooleanLiteral(true);
        }
        if ("false".equalsIgnoreCase(expr) || "b'0'".equalsIgnoreCase(expr)) {
            return getBooleanLiteral(false);
        }
        if (NUMBER_LITERAL.matcher(expr).matches()) {
            if (booleanColumn && ("0".equals(expr) || "1".equals(expr))) {
                return getBooleanLiteral("1".equals(expr));
            }
            return expr;
        }
        Matcher stringMatcher = STRING_LITERAL.matcher(expr);
        if (stringMatcher.matches()) {
            String value = stringMatcher.group(1).replace("''", "'");
            if (NUMBER_LITERAL.matcher(value).matches() && isNumericType(dataType)) {
                return value;
            }
            return getStringLiteral(value);
        }
        if (CURRENT_TIMESTAMP.matcher(expr).matches()) {
            return dataType == Types.DATE ? getCurrentDateExpression() : getCurrentTimestampExpression();
        }
        if (CURRENT_DATE.matcher(expr).matches()) {
            return getCurrentDateExpression();
        }
        return null;
    }

    private static boolean isWrapped(String expr) {
        int depth = 0;
        for (int i = 0; i < expr.length(); i++) {
            char c = expr.charAt(i);
            if (c == '(') {
                depth++;
            } else if (c == ')') {
                depth--;
                if (depth == 0 && i != expr.length() - 1) {
                    return false;
                }
            }
        }
        return depth == 0;
    }

    protected static boolean isNumericType(int dataType) {
        switch (dataType) {
            case Types.TINYINT:
            case Types.SMALLINT:
            case Types.INTEGER:
            case Types.BIGINT:
            case Types.FLOAT:
            case Types.REAL:
            case Types.DOUBLE:
            case Types.NUMERIC:
            case Types.DECIMAL:
                return true;
            default:
                return false;
        }
    }

