    /**
     * Creates a sequence, returns <code>null</code> if sequences are not supported
     */
    public String getCreateSequenceStatement(String catalog, String schema, String sequenceName, long startValue,
                                             long increment, Long minValue, Long maxValue, boolean cycle,
                                             Long cacheSize, String dataType) {
        if (!isSequenceSupported()) {
            return null;
        }
        StringBuilder sql = new StringBuilder("CREATE SEQUENCE ");
        sql.append(getQualifiedSequenceName(catalog, schema, sequenceName));
        sql.append(" START WITH ").append(startValue).append(" INCREMENT BY ").append(increment);
        if (minValue != null) {
            sql.append(" MINVALUE ").append(minValue);
        }
        if (maxValue != null && maxValue < Long.MAX_VALUE) {
            sql.append(" MAXVALUE ").append(maxValue);
        }
        if (cycle) {
            sql.append(" CYCLE");
        }
        if (cacheSize != null && cacheSize > 1) {
            sql.append(" CACHE ").append(cacheSize);
        }
        return sql.toString();
    }

