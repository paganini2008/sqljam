    private LocalDateTime truncateNanos(LocalDateTime value) {
        return value.withNano(truncateNanos(value.getNano()));
    }

    private LocalTime truncateNanos(LocalTime value) {
        return value.withNano(truncateNanos(value.getNano()));
    }

    private int truncateNanos(int nanos) {
        int unit = (int) Math.pow(10, 9 - getMaxFractionalSecondsPrecision());
        return nanos / unit * unit;
    }

    private static boolean isTemporalType(int dataType) {
        return dataType == Types.DATE || dataType == Types.TIME || dataType == Types.TIMESTAMP;
    }

    /**
     * Parses date/time text, returns the text itself if it can not be parsed
     */
    static Object parseTemporal(String text, int dataType) {
        String value = text.trim();
        try {
            if (dataType == Types.TIME) {
                return LocalTime.parse(value);
            }
            if (value.length() == 10) {
                LocalDate date = LocalDate.parse(value);
                return dataType == Types.DATE ? date : date.atStartOfDay();
            }
            LocalDateTime dateTime = LocalDateTime.parse(value.replace(' ', 'T'));
            return dataType == Types.DATE ? dateTime.toLocalDate() : dateTime;
        } catch (RuntimeException e) {
            if (value.matches("-?\\d{10,}")) {
                // Epoch milliseconds
                LocalDateTime dateTime = new Timestamp(Long.parseLong(value)).toLocalDateTime();
                return dataType == Types.DATE ? dateTime.toLocalDate() : dateTime;
            }
            return text;
        }
    }

    private static Object toLong(Object value) {
        if (value instanceof byte[]) {
            long result = 0;
            for (byte b : (byte[]) value) {
                result = (result << 8) | (b & 0xFF);
            }
            return result;
        } else if (value instanceof Boolean) {
            return (Boolean) value ? 1L : 0L;
        } else if (value instanceof Number) {
            return ((Number) value).longValue();
        } else if (value instanceof CharSequence && value.toString().matches("[01]+")) {
            return Long.parseLong(value.toString(), 2);
        }
        return value;
    }

