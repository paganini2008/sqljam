    /**
     * Dialect of the given version of this database type (e.g. Oracle11gDialect), settings of this dialect are copied
     */
    public Dialect forVersion(int majorVersion, int minorVersion) {
        Dialect dialect = getDbType().createDialect(majorVersion, minorVersion);
        dialect.setSourceDbType(sourceDbType);
        dialect.setIdentifierCase(identifierCase);
        dialect.setTargetCatalogName(targetCatalogName);
        dialect.setTargetSchemaName(targetSchemaName);
        dialect.setSourceSchemaPreserved(sourceSchemaPreserved);
        return dialect;
    }

    /**
     * Whether the database version is greater than or equal to the given version. Unknown version is treated as the
     * latest version.
     */
    public boolean isVersionAtLeast(int majorVersion, int minorVersion) {
        if (databaseMajorVersion < 0) {
            return true;
        }
        return databaseMajorVersion > majorVersion
                || (databaseMajorVersion == majorVersion && databaseMinorVersion >= minorVersion);
    }

