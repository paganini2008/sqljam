    private static final Pattern STRING_LITERAL = Pattern.compile("[nN]?'((?:[^']|'')*)'");
    private static final Pattern PG_CAST = Pattern.compile("^(.*?)::[A-Za-z_][A-Za-z0-9_ .\"]*(\\(\\d+(,\\s*\\d+)?\\))?(\\[\\])?$",
            Pattern.DOTALL);
    private static final Pattern CURRENT_TIMESTAMP = Pattern.compile(
            "(?i)(current_timestamp|now|localtimestamp|getdate|getutcdate|sysdatetime|sysutcdatetime|sysdate|systimestamp|"
                    + "transaction_timestamp|statement_timestamp|clock_timestamp|utc_timestamp|current_datetime)"
                    + "\\s*(\\(\\s*\\d*\\s*\\))?");
    private static final Pattern CURRENT_DATE = Pattern.compile("(?i)(current_date|curdate)\\s*(\\(\\s*\\))?");
    private static final DateTimeFormatter TIMESTAMP_FORMATTER = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
