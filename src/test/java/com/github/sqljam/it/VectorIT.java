    /**
     * A database of PostgreSQL without pgvector: the vectors are text, vector indexes are skipped
     */
    @Test
    void withoutPgvector() throws Exception {
        assumeTrue(ItDatabase.POSTGRESQL.isAvailable());
        createPgvectorSource();
        String url = DbType.POSTGRESQL.getUrl(ItDatabase.Settings.get(ItDatabase.POSTGRESQL, "host"), Integer.parseInt(
                ItDatabase.Settings.get(ItDatabase.POSTGRESQL, "port")), "sjit_novector");
        try (Connection connection = DriverManager.getConnection(url, ItDatabase.POSTGRESQL.getUsername(),
                ItDatabase.POSTGRESQL.getPassword()); Statement statement = connection.createStatement();
             ResultSet rs = statement.executeQuery("SELECT to_regtype('vector') IS NULL")) {
            assumeTrue(rs.next() && rs.getBoolean(1), "sjit_novector has pgvector");
            statement.execute("CREATE SCHEMA IF NOT EXISTS sjit_dst");
        }
        ImportExporter importExporter = new ImportExporter();
        configureSource(ItDatabase.POSTGRESQL, importExporter.getExportConfiguration());
        ItDatabase.POSTGRESQL.configureTarget(importExporter.getImportConfiguration());
        importExporter.getImportConfiguration().setUrl(url);
        importExporter.getImportConfiguration().setTargetCatalogName("sjit_novector");
        CollectingListener listener = new CollectingListener();
        importExporter.setExportListener(listener);
        importExporter.exportDdlAndData();
        assertEquals(List.of(), listener.getErrors());
        assertTrue(listener.getMessages().stream().noneMatch(message -> message.startsWith("Target database features")),
                listener.getMessages().toString());
        try (Connection connection = DriverManager.getConnection(url, ItDatabase.POSTGRESQL.getUsername(),
                ItDatabase.POSTGRESQL.getPassword())) {
            Map<String, Map<String, Object>> columns = columns(ItDatabase.POSTGRESQL, connection, TABLE);
            for (String column : new String[]{"embedding", "embedding_large", "small", "tags"}) {
                assertEquals("text", columns.get(column).get("TYPE_NAME"), column);
            }
            assertEquals(List.of(), indexDefinitions(connection, "sjit_dst"));
            assertRows(ItDatabase.POSTGRESQL, connection, TABLE, columns);
        }
    }

    /**
     * SQL, Parquet and CSV packages of vectors for PostgreSQL: the vector types and indexes are restored by
     * schema.sql
     */
    @Test
    void packagesOfVectors() throws Exception {
        assumeTrue(ItDatabase.POSTGRESQL.isAvailable());
        createPgvectorSource();
        for (String format : new String[]{"sql", "parquet", "csv"}) {
            File dir = new File(ItDatabase.DATA_DIR, "vector/" + format);
            FileUtils.deleteQuietly(dir);
            CollectingListener listener = new CollectingListener();
            if ("sql".equals(format)) {
                ScriptExporter exporter = new ScriptExporter(dir, DataFileStrategy.SINGLE_FILE, 64 * 1024);
                configureSource(ItDatabase.POSTGRESQL, exporter.getConfiguration());
                exporter.setTargetDbType(DbType.POSTGRESQL);
                exporter.setTargetSchemaName(ItDatabase.POSTGRESQL.getTargetSchema());
                exporter.setExportListener(listener);
                exporter.exportDdlAndData();
            } else {
                DataFileExporter exporter = "csv".equals(format) ? new CsvExporter(dir) : new ParquetExporter(dir);
                configureSource(ItDatabase.POSTGRESQL, exporter.getConfiguration());
                exporter.setTargetDbType(DbType.POSTGRESQL);
                exporter.setTargetSchemaName(ItDatabase.POSTGRESQL.getTargetSchema());
                exporter.setExportListener(listener);
                exporter.exportDdlAndData();
            }
            assertEquals(List.of(), listener.getErrors(), format);
            try (Connection connection = ItDatabase.POSTGRESQL.getTargetConnection();
                 Statement statement = connection.createStatement()) {
                statement.execute("DROP TABLE IF EXISTS " + ItDatabase.POSTGRESQL.getTargetSchema() + "." + TABLE);
                AbstractFileImporter importer = AbstractFileImporter.forDirectory(dir, connection, DbType.POSTGRESQL);
                CollectingListener importListener = new CollectingListener();
                importer.setExportListener(importListener);
                importer.importDirectory(dir);
                assertEquals(List.of(), importListener.getErrors(), format);
                Map<String, Map<String, Object>> columns = columns(ItDatabase.POSTGRESQL, connection, TABLE);
                assertEquals(VectorType.dense(VectorType.Element.FLOAT16, 2560), VectorType.of(columns.get(
                        "embedding_large")), format);
                assertEquals(new VectorType(VectorType.Element.FLOAT32, 8, true), VectorType.of(columns.get("tags")),
                        format);
                assertRows(ItDatabase.POSTGRESQL, connection, TABLE, columns);
            }
            assertEquals(3, indexDefinitions(ItDatabase.POSTGRESQL.getTargetSchema()).size(), format);
        }
    }

    /**
     * A user of Oracle without SELECT_CATALOG_ROLE reads no distances of vector indexes (V$VECTOR_INDEX) and no
     * vector memory (v$parameter): the default distance is taken, IVF indexes are created
     */
    @Test
    void oracleUserWithoutCatalogViews() throws Exception {
        assumeTrue(ItDatabase.ORACLE.isAvailable() && ItDatabase.POSTGRESQL.isAvailable());
        createVectorSource(ItDatabase.ORACLE);
        String url = ItDatabase.ORACLE.getSourceUrl();
        try (Connection admin = ItDatabase.ORACLE.getSourceConnection(); Statement statement = admin.createStatement()) {
            statement.execute("GRANT SELECT ON " + ItDatabase.ORACLE.getSourceSchema() + "." + TABLE.toUpperCase(
                    Locale.ENGLISH) + " TO SJIT_READER");
        }
        try (Connection reader = DriverManager.getConnection(url, "SJIT_READER", "Sjit_reader123")) {
            OracleFeatures features = new OracleFeatures(reader);
            assertTrue(features.features.contains(DatabaseFeature.VECTOR));
            assertFalse(features.features.contains(DatabaseFeature.HNSW_INDEX), "v$parameter is not granted");
            // The table of ADMIN read by the user: the index is found, its distance is the default one
            MetaDataOperations operations = DbType.ORACLE.createMetaDataOperations();
            VectorIndex index = operations.getIndexInfos(reader.getMetaData(), null, ItDatabase.ORACLE
                    .getSourceSchema(), TABLE.toUpperCase(Locale.ENGLISH)).stream().map(VectorIndex::of)
                    .filter(java.util.Objects::nonNull).findFirst().orElse(null);
            assertNotNull(index);
            assertEquals(VectorIndex.Distance.COSINE, index.getDistance());

            // A target of the user: IVF index of the HNSW index of pgvector
            createPgvectorSource();
            ImportExporter importExporter = new ImportExporter();
            configureSource(ItDatabase.POSTGRESQL, importExporter.getExportConfiguration());
            importExporter.getImportConfiguration().setDbType(DbType.ORACLE);
            importExporter.getImportConfiguration().setUrl(url);
            importExporter.getImportConfiguration().setUsername("SJIT_READER");
            importExporter.getImportConfiguration().setPassword("Sjit_reader123");
            importExporter.getImportConfiguration().setTargetSchemaName("SJIT_READER");
            CollectingListener listener = new CollectingListener();
            importExporter.setExportListener(listener);
            importExporter.exportDdlAndData();
            assertEquals(List.of(), listener.getErrors());
            try (Statement statement = reader.createStatement(); ResultSet rs = statement.executeQuery(
                    "SELECT INDEX_SUBTYPE FROM USER_INDEXES WHERE TABLE_NAME = 'SJV_DOC' AND INDEX_TYPE = 'VECTOR'"
                            + " ORDER BY INDEX_NAME")) {
                List<String> kinds = new ArrayList<>();
                while (rs.next()) {
                    kinds.add(rs.getString(1));
                }
                assertFalse(kinds.isEmpty());
                assertTrue(kinds.stream().allMatch(kind -> kind.contains("IVF")), kinds.toString());
            }
            try (Statement statement = reader.createStatement()) {
                statement.execute("DROP TABLE SJIT_READER.SJV_DOC PURGE");
            }
        }
    }

