    static void configureSource(ItDatabase source, Exporter.ExportConfiguration configuration) {
        source.configureSource(configuration);
        configuration.setIncludedTableNamePattern(PATTERN);
    }

    static CollectingListener copy(ItDatabase source, ItDatabase target, boolean skipErrors) throws Exception {
        ImportExporter importExporter = new ImportExporter();
        configureSource(source, importExporter.getExportConfiguration());
        target.configureTarget(importExporter.getImportConfiguration());
        importExporter.getImportConfiguration().setSkipErrors(skipErrors);
        CollectingListener listener = new CollectingListener();
        importExporter.setExportListener(listener);
        try {
            importExporter.exportDdlAndData();
        } catch (Exception e) {
            if (!skipErrors) {
                throw new AssertionError(e.getMessage() + "\nErrors: " + listener.getErrors(), e);
            }
        }
        return listener;
    }

    /**
     * Columns of the target table by their names in lower case, read by the metadata of SqlJam: the vector types
     * of the target are its detected types
     */
    static Map<String, Map<String, Object>> columns(ItDatabase target, Connection connection, String table)
            throws SQLException {
        Map<String, Map<String, Object>> columns = new LinkedHashMap<>();
        MetaDataOperations operations = target.getDbType().createMetaDataOperations();
        for (Map<String, Object> column : operations.getColumnInfos(connection.getMetaData(),
                catalog(target, connection), schema(target), tableName(target, table))) {
            columns.put(((String) column.get("COLUMN_NAME")).toLowerCase(Locale.ENGLISH), column);
        }
        assertFalse(columns.isEmpty(), "Columns of " + table + " in " + target);
        return columns;
    }

    /**
     * Vector indexes of the target table by their columns in lower case
     */
    static Map<String, VectorIndex> vectorIndexes(ItDatabase target, Connection connection, String table)
            throws SQLException {
        Map<String, VectorIndex> indexes = new LinkedHashMap<>();
        MetaDataOperations operations = target.getDbType().createMetaDataOperations();
        for (Map<String, Object> index : operations.getIndexInfos(connection.getMetaData(), catalog(target,
                connection), schema(target), tableName(target, table))) {
            VectorIndex vectorIndex = VectorIndex.of(index);
            if (vectorIndex != null) {
                indexes.put(((String) index.get("COLUMN_NAME")).toLowerCase(Locale.ENGLISH), vectorIndex);
            }
        }
        return indexes;
    }

