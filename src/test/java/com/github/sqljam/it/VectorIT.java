    @BeforeAll
    static void loadEmbeddings() throws IOException {
        if (!EMBEDDINGS.isEmpty()) {
            return;
        }
        for (String line : Files.readAllLines(Paths.get("src/test/resources/vector/embeddings.tsv"),
                StandardCharsets.UTF_8)) {
            if (!line.startsWith("#") && !line.isBlank()) {
                EMBEDDINGS.add(line.split("\t"));
            }
        }
        assertEquals(ROWS - 1, EMBEDDINGS.size());
    }

    /**
     * Rows of the source table: id, title, embedding, embedding_large, small, tags
     */
    static List<Object[]> rows() {
        List<Object[]> rows = new ArrayList<>();
        for (String[] embedding : EMBEDDINGS) {
            int id = Integer.parseInt(embedding[0]);
            rows.add(new Object[]{id, embedding[1], embedding[2], embedding[3],
                    String.format("[%d,%s,-%d.5]", id, id % 2 == 0 ? "0" : "0.25", id),
                    String.format("{%d:1,%d:0.5}/8", id, id % 8 + 1)});
        }
        // Boundary values: an embedding of negated elements, tiny and huge elements, no large embedding, a sparse
        // vector without elements
        String[] last = EMBEDDINGS.get(EMBEDDINGS.size() - 1);
        String negated = "[" + java.util.Arrays.stream(last[2].substring(1, last[2].length() - 1).split(","))
                .map(item -> item.startsWith("-") ? item.substring(1) : "-" + item).collect(Collectors.joining(","))
                + "]";
        rows.add(new Object[]{BOUNDARY_ID, "Grenzwerte 境界値 '\"\\", negated, null, "[1e-5,-0.5,1e18]", "{}/8"});
        return rows;
    }

    static void createPgvectorSource() throws Exception {
        try (Connection connection = ItDatabase.POSTGRESQL.getSourceConnection();
             Statement statement = connection.createStatement()) {
            String table = ItDatabase.POSTGRESQL.getSourceSchema() + "." + TABLE;
            statement.execute("DROP TABLE IF EXISTS " + table);
            statement.execute("CREATE TABLE " + table + " (id int PRIMARY KEY, title text NOT NULL,"
                    + " embedding vector(1024) NOT NULL, embedding_large halfvec(2560), small vector(3),"
                    + " tags sparsevec(8))");
            statement.execute("COMMENT ON COLUMN " + table + ".embedding IS 'bge-m3'");
            try (PreparedStatement ps = connection.prepareStatement("INSERT INTO " + table
                    + " VALUES (?, ?, ?, ?, ?, ?)")) {
                for (Object[] row : rows()) {
                    for (int i = 0; i < row.length; i++) {
                        ps.setObject(i + 1, row[i]);
                    }
                    ps.addBatch();
                }
                ps.executeBatch();
            }
            statement.execute("CREATE INDEX sjv_doc_embedding ON " + table
                    + " USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64)");
            statement.execute("CREATE INDEX sjv_doc_large ON " + table
                    + " USING hnsw (embedding_large halfvec_l2_ops)");
            statement.execute("CREATE INDEX sjv_doc_small ON " + table
                    + " USING ivfflat (small vector_l2_ops) WITH (lists = 1)");
        }
    }

