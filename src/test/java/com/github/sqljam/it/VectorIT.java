    /**
     * Every element of every vector of the target equals the source, vectors kept as text included
     */
    static void assertRows(ItDatabase target, Connection connection, String table,
                           Map<String, Map<String, Object>> columns) throws SQLException {
        Dialect dialect = target.getDbType().createDialect();
        // Vectors are read as text, like by an export into another database
        dialect.setReadTargetDbType(DbType.POSTGRESQL);
        String[] names = {"id", "title", "embedding", "embedding_large", "small", "tags"};
        String select = java.util.Arrays.stream(names).map(name -> dialect.getSelectColumnExpression(
                (String) columns.get(name).get("COLUMN_NAME"), (String) columns.get(name).get("TYPE_NAME")))
                .collect(Collectors.joining(", "));
        String qualified = dialect.getSourceTableName(catalog(target, connection), schema(target),
                tableName(target, table));
        List<Object[]> expected = rows();
        try (Statement statement = connection.createStatement(); ResultSet rs = statement.executeQuery(
                "SELECT " + select + " FROM " + qualified + " ORDER BY 1")) {
            int count = 0;
            while (rs.next()) {
                Object[] row = expected.get(count++);
                String label = target + " row " + row[0];
                assertEquals(((Number) row[0]).longValue(), ((Number) rs.getObject(1)).longValue(), label);
                assertEquals(row[1], rs.getString(2), label);
                for (int i = 2; i < names.length; i++) {
                    Object value = dialect.getColumnValue(rs, i + 1, rs.getMetaData().getColumnType(i + 1),
                            rs.getMetaData().getColumnTypeName(i + 1));
                    String text = value != null ? value.toString() : null;
                    if (row[i] == null) {
                        // An empty array of ClickHouse is not NULL, text of a nullable vector is
                        assertNull(text, label + " " + names[i]);
                    } else if ("embedding_large".equals(names[i])) {
                        // 16-bit floats of halfvec: 11 bits of precision, subnormal below 6.1e-5
                        assertVectorEquals((String) row[i], text, label + " " + names[i], HALF_TOLERANCE, 1e-7);
                    } else {
                        assertVectorEquals((String) row[i], text, label + " " + names[i]);
                    }
                }
            }
            assertEquals(ROWS, count, target + " rows");
        }
    }

    static void assertVectorEquals(String expected, String actual, String label) {
        assertVectorEquals(expected, actual, label, TOLERANCE, 1e-12);
    }

    /**
     * Elements are equal by the relative difference, or by the absolute difference of tiny elements
     */
    static void assertVectorEquals(String expected, String actual, String label, double relative, double absolute) {
        assertNotNull(actual, label);
        VectorType.Values expectedValues = VectorType.parseValues(expected);
        VectorType.Values actualValues = VectorType.parseValues(actual);
        assertNotNull(actualValues, label + ": " + actual);
        float[] expectedFloats = expectedValues.toFloats();
        float[] actualFloats = actualValues.toFloats();
        assertEquals(expectedFloats.length, actualFloats.length, label + " dimensions");
        for (int i = 0; i < expectedFloats.length; i++) {
            double difference = Math.abs(expectedFloats[i] - actualFloats[i]);
            assertTrue(difference <= relative * Math.abs(expectedFloats[i]) || difference <= absolute,
                    label + " element " + i + ": " + expectedFloats[i] + " != " + actualFloats[i]);
        }
    }

    /**
     * Ids of the 3 nearest neighbors of the embedding of row 1 by the cosine distance, searched by the database
     */
    static List<Integer> nearest(ItDatabase database, Connection connection) throws SQLException {
        boolean source = connection == null;
        DbType dbType = database.getDbType();
        String schema = source ? database.getSourceSchema() : database.getTargetSchema();
        String table = dbType == DbType.MYSQL || dbType == DbType.MARIADB || schema == null ? tableName(database, TABLE)
                : schema + "." + tableName(database, TABLE);
        String query = "(SELECT embedding FROM " + table + " WHERE id = 1)";
        String sql;
        switch (dbType) {
            case POSTGRESQL:
                sql = "SELECT id FROM " + table + " ORDER BY embedding <=> " + query + " LIMIT 3";
                break;
            case MARIADB:
                sql = "SELECT id FROM " + table + " ORDER BY VEC_DISTANCE_COSINE(embedding, " + query + ") LIMIT 3";
                break;
            case ORACLE:
                sql = "SELECT id FROM " + table + " ORDER BY VECTOR_DISTANCE(embedding, " + query + ", COSINE)"
                        + " FETCH FIRST 3 ROWS ONLY";
                break;
            case SQLSERVER:
                sql = "SELECT TOP 3 id FROM " + table + " ORDER BY VECTOR_DISTANCE('cosine', embedding, " + query
                        + ")";
                break;
            case DB2:
                sql = "SELECT id FROM " + table + " ORDER BY VECTOR_DISTANCE(embedding, " + query + ", COSINE)"
                        + " FETCH FIRST 3 ROWS ONLY";
                break;
            case DUCKDB:
                sql = "SELECT id FROM " + table + " ORDER BY array_cosine_distance(embedding, " + query + ") LIMIT 3";
                break;
            case CLICKHOUSE:
                sql = "SELECT id FROM " + table + " ORDER BY cosineDistance(embedding, " + query + ") LIMIT 3";
                break;
            default:
                throw new IllegalArgumentException(database.name());
        }
        Connection opened = source ? database.getSourceConnection() : null;
        // Operators of pgvector are found by the search path, e.g. of a connection with currentSchema
        dbType.createDialect().prepareSession(source ? opened : connection);
        try (Statement statement = (source ? opened : connection).createStatement();
             ResultSet rs = statement.executeQuery(sql)) {
            List<Integer> ids = new ArrayList<>();
            while (rs.next()) {
                ids.add(((Number) rs.getObject(1)).intValue());
            }
            return ids;
        } finally {
            if (opened != null) {
                opened.close();
            }
        }
    }

    /**
     * The 3 nearest neighbors of the embedding of row 1 by the cosine distance, computed of the embeddings
     */
    static List<Integer> nearestOfEmbeddings() {
        float[] first = VectorType.parseValues(EMBEDDINGS.get(0)[2]).toFloats();
        return EMBEDDINGS.stream().sorted(java.util.Comparator.comparingDouble(embedding -> cosineDistance(first,
                VectorType.parseValues(embedding[2]).toFloats()))).limit(3).map(embedding -> Integer.parseInt(
                embedding[0])).collect(Collectors.toList());
    }

    private static double cosineDistance(float[] a, float[] b) {
        double dot = 0;
        double normA = 0;
        double normB = 0;
        for (int i = 0; i < a.length; i++) {
            dot += a[i] * b[i];
            normA += a[i] * a[i];
            normB += b[i] * b[i];
        }
        return 1 - dot / (Math.sqrt(normA) * Math.sqrt(normB));
    }

    private static List<String> indexDefinitions(String schema) throws SQLException {
        try (Connection connection = ItDatabase.POSTGRESQL.getTargetConnection()) {
            return indexDefinitions(connection, schema);
        }
    }

    /**
     * Access methods, columns and options of the indexes of the table in PostgreSQL, the primary key excluded
     */
    private static List<String> indexDefinitions(Connection connection, String schema) throws SQLException {
        List<String> definitions = new ArrayList<>();
        try (PreparedStatement ps = connection.prepareStatement("SELECT indexdef FROM pg_indexes WHERE schemaname = ?"
                + " AND tablename = ? AND indexname NOT LIKE '%pkey'")) {
            ps.setString(1, schema);
            ps.setString(2, TABLE);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    // Operator classes outside of the search path are qualified, e.g. public.vector_cosine_ops
                    definitions.add(rs.getString(1).replaceAll("^.* USING ", "").replace("public.", ""));
                }
            }
        }
        // Sorted without the index names, their order depends on the collation of the database
        Collections.sort(definitions);
        return definitions;
    }
