        for (Map.Entry<String, Object[]> entry : readers.entrySet()) {
            ItDatabase database = (ItDatabase) entry.getValue()[0];
            if (!database.isAvailable()) {
                continue;
            }
            try (Connection connection = DriverManager.getConnection(database.getSourceUrl(),
                    (String) entry.getValue()[1], (String) entry.getValue()[2])) {
                Set<DatabaseFeature> features = database.getDbType().createDialect().readDatabaseFeatures(connection);
                assertTrue(features.contains(DatabaseFeature.VECTOR), entry.getKey() + ": " + features);
            }
        }
