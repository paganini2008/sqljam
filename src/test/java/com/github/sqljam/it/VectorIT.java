    /**
     * Source table of a database with vectors: id, embedding of 1024 dimensions NOT NULL and a vector index of it
     * where the database has one
     */
    static void createVectorSource(ItDatabase source) throws Exception {
        try (Connection connection = source.getSourceConnection(); Statement statement = connection.createStatement()) {
            String schema = source.getSourceSchema();
            String table = (schema != null && source.getDbType() != DbType.MYSQL && source.getDbType() != DbType.MARIADB
                    ? schema + "." : "") + TABLE;
            String drop = "DROP TABLE " + table;
            String create;
            String index = null;
            String vector = "?";
            switch (source.getDbType()) {
                case MYSQL:
                    create = "CREATE TABLE " + table + " (id INT PRIMARY KEY, embedding VECTOR(1024) NOT NULL)";
                    vector = "STRING_TO_VECTOR(?)";
                    break;
                case MARIADB:
                    create = "CREATE TABLE " + table + " (id INT PRIMARY KEY, embedding VECTOR(1024) NOT NULL,"
                            + " VECTOR INDEX sjv_doc_embedding (embedding) M=16 DISTANCE=cosine)";
                    vector = "VEC_FromText(?)";
                    break;
                case ORACLE:
                    drop = "BEGIN EXECUTE IMMEDIATE 'DROP TABLE " + table + " PURGE'; EXCEPTION WHEN OTHERS THEN"
                            + " NULL; END;";
                    create = "CREATE TABLE " + table + " (ID NUMBER(10) PRIMARY KEY, EMBEDDING VECTOR(1024, FLOAT32)"
                            + " NOT NULL)";
                    index = "CREATE VECTOR INDEX SJV_DOC_EMBEDDING ON " + table + " (EMBEDDING) ORGANIZATION"
                            + " INMEMORY NEIGHBOR GRAPH DISTANCE COSINE PARAMETERS (TYPE HNSW, NEIGHBORS 16,"
                            + " EFCONSTRUCTION 64)";
                    break;
                case SQLSERVER:
                    drop = "DROP TABLE IF EXISTS " + table;
                    create = "CREATE TABLE " + table + " (id INT PRIMARY KEY, embedding VECTOR(1024) NOT NULL)";
                    break;
                case DB2:
                    create = "CREATE TABLE " + table + " (ID INT NOT NULL PRIMARY KEY, EMBEDDING VECTOR(1024, FLOAT32)"
                            + " NOT NULL)";
                    index = "CREATE VECTOR INDEX " + schema + ".SJV_DOC_EMBEDDING ON " + table
                            + " (EMBEDDING) WITH DISTANCE COSINE";
                    vector = "VECTOR(CAST(? AS CLOB), 1024, FLOAT32)";
                    break;
                case DUCKDB:
                    drop = "DROP TABLE IF EXISTS " + table;
                    create = "CREATE TABLE " + table + " (id INTEGER PRIMARY KEY, embedding FLOAT[1024] NOT NULL)";
                    vector = "CAST(? AS FLOAT[1024])";
                    break;
                case CLICKHOUSE:
                    drop = "DROP TABLE IF EXISTS " + table;
                    create = "CREATE TABLE " + table + " (id UInt32, embedding Array(Float32), INDEX"
                            + " sjv_doc_embedding embedding TYPE vector_similarity('hnsw', 'cosineDistance', 1024)"
                            + " GRANULARITY 100000000) ENGINE = MergeTree ORDER BY id";
                    break;
                default:
                    throw new IllegalArgumentException(source.name());
            }
            try {
                statement.execute(drop);
            } catch (SQLException e) {
                // The table does not exist
            }
            statement.execute(create);
            if (index != null) {
                statement.execute(index);
            }
            try (PreparedStatement ps = connection.prepareStatement("INSERT INTO " + table + " VALUES (?, "
                    + vector + ")")) {
                for (String[] embedding : EMBEDDINGS) {
                    ps.setInt(1, Integer.parseInt(embedding[0]));
                    ps.setString(2, embedding[2]);
                    ps.addBatch();
                }
                ps.executeBatch();
            }
            if (!connection.getAutoCommit()) {
                connection.commit();
            }
        }
    }

    @ParameterizedTest(name = "{0} into pgvector")
    @EnumSource(value = ItDatabase.class, names = {"MYSQL", "MARIADB", "ORACLE", "SQLSERVER", "DB2", "DUCKDB",
            "CLICKHOUSE"})
    void vectorsIntoPgvector(ItDatabase source) throws Exception {
        assumeTrue(source.isAvailable() && ItDatabase.POSTGRESQL.isAvailable());
        assumeTrue(AbstractImportIT.isTargetSelected(ItDatabase.POSTGRESQL));
        createVectorSource(source);
        CollectingListener listener = copy(source, ItDatabase.POSTGRESQL, false);
        assertEquals(List.of(), listener.getErrors(), source + " into pgvector");
        try (Connection connection = ItDatabase.POSTGRESQL.getTargetConnection()) {
            Map<String, Map<String, Object>> columns = columns(ItDatabase.POSTGRESQL, connection, TABLE);
            assertEquals(VectorType.dense(VectorType.Element.FLOAT32, 1024), VectorType.of(columns.get("embedding")),
                    source.name());
            Map<String, VectorIndex> indexes = vectorIndexes(ItDatabase.POSTGRESQL, connection, TABLE);
            if (source == ItDatabase.MYSQL || source == ItDatabase.SQLSERVER || source == ItDatabase.DUCKDB) {
                // These have no vector indexes
                assertTrue(indexes.isEmpty(), source + ": " + indexes);
            } else {
                assertEquals(VectorIndex.Distance.COSINE, indexes.get("embedding").getDistance(), source.name());
            }
            try (Statement statement = connection.createStatement(); ResultSet rs = statement.executeQuery(
                    "SELECT id, embedding::text FROM " + ItDatabase.POSTGRESQL.getTargetSchema() + "." + TABLE
                            + " ORDER BY id")) {
                int count = 0;
                while (rs.next()) {
                    String[] embedding = EMBEDDINGS.get(count++);
                    assertEquals(Integer.parseInt(embedding[0]), rs.getInt(1));
                    assertVectorEquals(embedding[2], rs.getString(2), source + " row " + rs.getInt(1));
                }
                assertEquals(EMBEDDINGS.size(), count, source.name());
            }
            assertEquals(nearestOfEmbeddings(), nearest(ItDatabase.POSTGRESQL, connection), source.name());
        }
    }

