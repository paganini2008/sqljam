    @ParameterizedTest(name = "pgvector into {0}")
    @EnumSource(ItDatabase.class)
    void pgvectorIntoEveryDatabase(ItDatabase target) throws Exception {
        assumeTrue(AbstractImportIT.isTargetSelected(target));
        assumeTrue(ItDatabase.POSTGRESQL.isAvailable() && target.isAvailable());
        createPgvectorSource();
        CollectingListener listener = copy(ItDatabase.POSTGRESQL, target, false);
        assertEquals(List.of(), listener.getErrors(), "pgvector into " + target);

        try (Connection connection = target.getTargetConnection()) {
            Map<String, Map<String, Object>> columns = columns(target, connection, TABLE);
            Set<String> expected = VECTOR_COLUMNS.getOrDefault(target, Set.of());
            for (String column : new String[]{"embedding", "embedding_large", "small", "tags"}) {
                VectorType vectorType = VectorType.of(columns.get(column));
                assertEquals(expected.contains(column), vectorType != null, target + " " + column + " is a vector: "
                        + columns.get(column));
            }
            assertEquals(VectorType.dense(VectorType.Element.FLOAT32, 1024).getDimensions(),
                    expected.contains("embedding") ? VectorType.of(columns.get("embedding")).getDimensions()
                            : 1024, target + " dimensions");
            assertRows(target, connection, TABLE, columns);
            Map<String, VectorIndex> indexes = vectorIndexes(target, connection, TABLE);
            if (INDEXED.contains(target)) {
                assertNotNull(indexes.get("embedding"), target + " vector index of embedding: " + indexes);
                assertEquals(VectorIndex.Distance.COSINE, indexes.get("embedding").getDistance(), target.name());
            } else {
                assertTrue(indexes.isEmpty(), target + " has no vector indexes: " + indexes);
            }
            if (SEARCHABLE.contains(target)) {
                assertEquals(nearest(ItDatabase.POSTGRESQL, null), nearest(target, connection),
                        "nearest neighbors of " + target);
            }
        }
        if (target == ItDatabase.POSTGRESQL) {
            // The indexes of pgvector are copied as they are, vector_l2_ops is the default operator class of ivfflat
            assertEquals(List.of("hnsw (embedding vector_cosine_ops) WITH (m='16', ef_construction='64')",
                    "hnsw (embedding_large halfvec_l2_ops)", "ivfflat (small) WITH (lists='1')"),
                    indexDefinitions(ItDatabase.POSTGRESQL.getTargetSchema()));
        }
        assertFeatures(target, listener);
    }

    /**
     * The import tells the detected features of the target
     */
    private static void assertFeatures(ItDatabase target, CollectingListener listener) {
        String features = listener.getMessages().stream().filter(message -> message.startsWith(
                "Target database features")).findFirst().orElse("");
        if (VECTOR_COLUMNS.containsKey(target)) {
            assertTrue(features.contains(DatabaseFeature.VECTOR.name()), target + ": " + features);
        } else {
            assertEquals("", features, target.name());
        }
    }

