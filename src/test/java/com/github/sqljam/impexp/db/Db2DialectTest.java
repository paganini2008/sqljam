    @Test
    void ddl() {
        Db2Dialect dialect = new Db2Dialect();
        assertEquals(DbType.DB2, dialect.getDbType());
        assertEquals(IdentifierCase.UPPER, dialect.getStoredIdentifierCase());
        assertEquals(128, dialect.getMaxIdentifierLength());
        assertNull(dialect.getCreateUserStatement("U", "p"));
        assertNull(dialect.getCreateDatabaseStatement("db", "u"));
        assertEquals("CREATE SCHEMA S", dialect.getCreateSchemaStatement(null, "S", "u"));
        assertEquals("BEGIN IF NOT EXISTS (SELECT 1 FROM SYSCAT.SCHEMATA WHERE SCHEMANAME = 'SJIT') THEN EXECUTE"
                + " IMMEDIATE 'CREATE SCHEMA SJIT'; END IF; END", dialect.getCreateSchemaIfNotExistsStatement("SJIT"));
        assertEquals("CREATE TABLE T", dialect.getCreateTableStatement(null, null, "T"));
        assertEquals("DROP TABLE IF EXISTS T", dialect.getDropTableStatement(null, null, "T"));
        assertEquals("COMMENT ON COLUMN T.C IS 'x'", dialect.getCreateCommentStatement(null, null, "T", "C", "x"));
        assertEquals("CREATE UNIQUE INDEX IDX ON T (A)", dialect.getCreateIndexStatement(null, null, "T", false,
                new String[]{"A"}, "IDX", true, null));
        dialect.setTargetSchemaName("APP");
        assertEquals("CREATE INDEX APP.IDX ON APP.T (A)", dialect.getCreateIndexStatement(null, null, "T", false,
                new String[]{"A"}, "IDX", false, null));
        dialect.registerColumnTypeName("T", "BODY", "CLOB(2G)");
        assertNull(dialect.getCreateIndexStatement(null, null, "T", false, new String[]{"BODY"}, "IDX", false, null));
        dialect = new Db2Dialect();
        assertTrue(dialect.getCreateForeignKeyStatement(null, null, "T", "FK", new String[]{"A"}, "R",
                new String[]{"ID"}, "CASCADE", "SET DEFAULT").endsWith("REFERENCES R (ID)"));
        assertEquals("C INTEGER GENERATED ALWAYS AS (A * 2)", dialect.getGeneratedColumnStatement(null, null, "T",
                "C", Types.INTEGER, "integer", 10, 0, "A * 2", true));
        assertEquals("CURRENT TIMESTAMP", dialect.getCurrentTimestampExpression());
        assertEquals("CURRENT DATE", dialect.getCurrentDateExpression());
        assertNull(dialect.getSequenceNameStatement(null, null, "T", "ID"));
        assertNull(dialect.getDefaultSequenceName(null, null, "T", "ID"));
        assertNull(dialect.getAlterSequenceStartValueStatement(null, null, "T", "S", 1));
        assertNull(dialect.getCreatePartitionTableStatement(null, null, "T", "P"));
    }

    @Test
    void identitiesAndSequences() {
        Db2Dialect dialect = new Db2Dialect();
        assertTrue(dialect.isSingleIncrementalColumn());
        assertEquals("ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY", dialect.getIncrementalColumnStatement(
                null, null, "T", "ID", Types.BIGINT, "bigint", 19, 0, null, false).replaceAll("\\s+", " "));
        assertEquals("ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY", dialect.getIncrementalColumnStatement(
                null, null, "T", "ID", Types.INTEGER, "int", 10, 0, null, false).replaceAll("\\s+", " "));
        // An identity of a decimal type with scale is a BIGINT
        assertEquals("ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY", dialect.getIncrementalColumnStatement(
                null, null, "T", "ID", Types.DECIMAL, "decimal", 10, 2, null, false).replaceAll("\\s+", " "));
        assertEquals("ALTER TABLE T ALTER COLUMN ID RESTART WITH 10", dialect.getResetIdentityStatement(null, null,
                "T", "ID", 10));
        assertTrue(dialect.isSequenceSupported());
        assertEquals("CREATE SEQUENCE S AS BIGINT START WITH 1000 INCREMENT BY 10 MINVALUE 1 CYCLE CACHE 20",
                dialect.getCreateSequenceStatement(null, null, "S", 1000, 10, 1L, Long.MAX_VALUE, true, 20L, null));
        assertEquals("CREATE SEQUENCE S AS BIGINT START WITH 1 INCREMENT BY 1 NO CACHE",
                dialect.getCreateSequenceStatement(null, null, "S", 1, 1, null, null, false, 1L, null));
        assertEquals("BEGIN DECLARE CONTINUE HANDLER FOR SQLSTATE '42704' BEGIN END; EXECUTE IMMEDIATE"
                + " 'DROP SEQUENCE S'; END", dialect.getStatementBeforeSequenceCreated(null, null, "S")[0]);
    }

    @Test
    void literalsAndValues() {
        Db2Dialect dialect = new Db2Dialect();
        assertEquals("TRUE", dialect.getBooleanLiteral(true));
        assertEquals("FALSE", dialect.getBooleanLiteral(false));
        assertEquals("BX'CAFE'", dialect.getBinaryLiteral(new byte[]{(byte) 0xCA, (byte) 0xFE}));
        assertEquals("BX''", dialect.getEmptyLobLiteral(true));
        assertEquals("''", dialect.getEmptyLobLiteral(false));
        assertEquals("'it''s'", dialect.getStringLiteral("it's"));
        assertEquals("NULL", dialect.getStringLiteral(null));
        // Long literals are CLOB values joined together
        String literal = dialect.getStringLiteral("x".repeat(8001));
        assertTrue(literal.startsWith("CLOB('") && literal.endsWith("CLOB('x')"), literal);
        assertEquals("DECFLOAT('3.141592653589793238462643383279502')", dialect.getStringValue(null, null, "T", "C",
                new BigDecimal("3.141592653589793238462643383279502")));
        assertEquals("12.5", dialect.getStringValue(null, null, "T", "C", new BigDecimal("12.5")));
        dialect.registerColumnTypeName("T", "BITS", "CHAR(4) FOR BIT DATA");
        assertEquals("X'0102'", dialect.getStringValue(null, null, "T", "BITS", new byte[]{1, 2}));
        assertEquals("BX'0102'", dialect.getStringValue(null, null, "T", "C", new byte[]{1, 2}));
        dialect.registerColumnTypeName("T", "VARIANT", "CLOB(2G)");
        assertEquals("'5'", dialect.getStringValue(null, null, "T", "VARIANT", 5));
        assertEquals("5", dialect.getStringValue(null, null, "T", "C", 5));
        OffsetDateTime time = OffsetDateTime.of(2024, 2, 29, 12, 0, 0, 0, ZoneOffset.ofHours(8));
        assertEquals("'2024-02-29T12:00+08:00'", dialect.getTimestampWithTimeZoneLiteral(time));
        assertEquals("2024-02-29T12:00+08:00", dialect.getJdbcValue(time));
        assertEquals(5, dialect.getJdbcValue(5));
        assertTrue(dialect.isTargetTypeConversionRequired());
        assertEquals("5", dialect.getTargetJdbcValue(5, "CLOB"));
        assertEquals("12.50", dialect.getTargetJdbcValue(new BigDecimal("12.50"), "VARCHAR"));
        assertEquals("true", dialect.getTargetJdbcValue(true, "CHAR"));
        assertEquals(5, dialect.getTargetJdbcValue(5, "INTEGER"));
        assertEquals(5, dialect.getTargetJdbcValue(5, "VARCHAR () FOR BIT DATA"));
        assertEquals("x", dialect.getTargetJdbcValue("x", "CLOB"));
        assertEquals("TIME '23:59:59'", dialect.getTimeLiteral(java.time.LocalTime.of(23, 59, 59, 123000000)));
        assertEquals("TIME '00:00:00'", dialect.getTimeLiteral(java.time.LocalTime.MIDNIGHT));
        assertEquals("SELECT * FROM T ORDER BY ID OFFSET 10 ROWS FETCH NEXT 5 ROWS ONLY",
                dialect.getPageStatement("SELECT * FROM T", "ID", 5, 10));
        assertEquals("SELECT * FROM T OFFSET 0 ROWS FETCH NEXT 5 ROWS ONLY", dialect.getPageStatement("SELECT * FROM T",
                null, 5, 0));
    }

    @Test
    void upserts() {
        Db2Dialect dialect = new Db2Dialect();
        assertTrue(dialect.isUpsertSupported());
        assertEquals("MERGE INTO T AS tgt USING (VALUES (?,?)) AS src (ID,NAME) ON tgt.ID = src.ID WHEN MATCHED THEN"
                + " UPDATE SET tgt.NAME = src.NAME WHEN NOT MATCHED THEN INSERT (ID,NAME) VALUES (src.ID, src.NAME)",
                dialect.getUpsertStatement(null, null, "T", new String[]{"ID", "NAME"}, new String[]{"ID"},
                        new String[]{"NAME"}));
        // Rows of existing keys are kept
        assertEquals("MERGE INTO T AS tgt USING (VALUES (?,?)) AS src (ID,NAME) ON tgt.ID = src.ID WHEN NOT MATCHED"
                + " THEN INSERT (ID,NAME) VALUES (src.ID, src.NAME)", dialect.getUpsertStatement(null, null, "T",
                new String[]{"ID", "NAME"}, new String[]{"ID"}, new String[0]));
    }

    @Test
    void typesOfOtherDatabases() {
        Db2Dialect dialect = new Db2Dialect();
        dialect.setSourceDbType(DbType.POSTGRESQL);
        assertEquals("VARCHAR(300)", dialect.getColumnTypeName(Types.VARCHAR, "varchar", 100, 0));
        assertEquals("CLOB(2G)", dialect.getColumnTypeName(Types.VARCHAR, "varchar", 20000, 0));
        assertEquals("VARCHAR(32670)", dialect.getColumnTypeName(Types.VARCHAR, "varchar", 10890, 0));
        assertEquals("CLOB(2G)", dialect.getColumnTypeName(Types.VARCHAR, "text", 0, 0));
        assertEquals("CHAR(10 CODEUNITS32)", dialect.getColumnTypeName(Types.CHAR, "bpchar", 10, 0));
        assertEquals("VARCHAR(300)", dialect.getColumnTypeName(Types.CHAR, "bpchar", 100, 0));
        assertEquals("CLOB(2G)", dialect.getColumnTypeName(Types.OTHER, "jsonb", 0, 0));
        assertEquals("XML", dialect.getColumnTypeName(Types.SQLXML, "xml", 0, 0));
        assertEquals("BLOB(2G)", dialect.getColumnTypeName(Types.BINARY, "bytea", 0, 0));
        assertEquals("CHAR(36)", dialect.getColumnTypeName(Types.OTHER, "uuid", 0, 0));
        assertEquals("BOOLEAN", dialect.getColumnTypeName(Types.BIT, "bool", 1, 0));
        assertEquals("DECIMAL(19,4)", dialect.getColumnTypeName(Types.DOUBLE, "money", 0, 0));
        assertEquals("CLOB(2G)", dialect.getColumnTypeName(Types.ARRAY, "_int4", 0, 0));
        assertEquals("TIMESTAMP", dialect.getColumnTypeName(Types.TIMESTAMP, "timestamp", 26, 6));
        assertEquals("TIMESTAMP(3)", dialect.getColumnTypeName(Types.TIMESTAMP, "timestamp", 23, 3));
        assertEquals("VARCHAR(40)", dialect.getColumnTypeName(Types.TIMESTAMP_WITH_TIMEZONE, "timestamptz", 35, 6));
        assertEquals("DECIMAL(10,2)", dialect.getColumnTypeName(Types.NUMERIC, "numeric", 10, 2));
        // Numbers wider than DECIMAL(31) or without size
        assertEquals("DECFLOAT(34)", dialect.getColumnTypeName(Types.NUMERIC, "numeric", 0, 0));
        assertEquals("DECFLOAT(34)", dialect.getColumnTypeName(Types.NUMERIC, "numeric", 38, 2));
        assertEquals("VARCHAR(64)", dialect.getColumnTypeName(Types.OTHER, "inet", 0, 0));
        assertEquals("VARBINARY(16)", dialect.getColumnTypeName(Types.VARBINARY, "varbinary", 16, 0));
        assertEquals("BINARY(4)", dialect.getColumnTypeName(Types.BINARY, "binary", 4, 0));
        dialect.setSourceDbType(DbType.MYSQL);
        assertEquals("SMALLINT", dialect.getColumnTypeName(Types.SMALLINT, "year", 4, 0));
        assertEquals("VARCHAR(765)", dialect.getColumnTypeName(Types.CHAR, "enum('a','b')", 1, 0));
        assertEquals("BIGINT", dialect.getColumnTypeName(Types.BIT, "bit", 8, 0));
        assertEquals("CLOB(2G)", dialect.getColumnTypeName(Types.LONGVARCHAR, "longtext", 0, 0));
        assertEquals("BLOB(2G)", dialect.getColumnTypeName(Types.LONGVARBINARY, "longblob", 0, 0));
        dialect.setSourceDbType(DbType.SQLSERVER);
        assertEquals("VARCHAR(40)", dialect.getColumnTypeName(-155, "datetimeoffset", 34, 7));
    }

