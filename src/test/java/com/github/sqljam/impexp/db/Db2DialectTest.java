    @Test
    void errors() {
        Db2Dialect dialect = new Db2Dialect();
        assertTrue(dialect.isAlreadyExistsError(new SQLException("exists", "42710", -601)));
        assertTrue(dialect.isAlreadyExistsError(new SQLException("primary key", "42889", -624)));
        assertFalse(dialect.isAlreadyExistsError(new SQLException("syntax", "42601", -104)));
        assertEquals(31, dialect.getMaxNumericPrecision());
        assertEquals(9, dialect.getMaxFractionalSecondsPrecision());
        assertTrue(dialect.isPartitionSupported());
        Map<String, Object> detail = new HashMap<>();
        detail.put("PARTITION_CLAUSE", "PARTITION BY RANGE (Y) (PARTITION P STARTING (1) ENDING (2))");
        assertEquals("PARTITION BY RANGE (Y) (PARTITION P STARTING (1) ENDING (2))",
                dialect.getDefinePartitionTableStatement(null, null, "T", "RANGE", "Y", detail));
        dialect.setSourceDbType(DbType.ORACLE);
        assertNull(dialect.getDefinePartitionTableStatement(null, null, "T", "RANGE", "Y", detail));
    }

    @Test
    void catalogValues() {
        assertEquals("C_INTEGER * 2", Db2MetaDataOperations.getGenerationExpression("AS (C_INTEGER * 2)"));
        assertEquals("A + B", Db2MetaDataOperations.getGenerationExpression("A + B"));
        assertNull(Db2MetaDataOperations.getGenerationExpression("  "));
        List<Map<String, Object>> partitions = List.of(
                partition("P2023", "MINVALUE", "Y", "2023", "Y"),
                partition("p max", "2025", "N", "MAXVALUE", "Y"));
        assertEquals("PARTITION BY RANGE (SALE_YEAR) (PARTITION P2023 STARTING (MINVALUE) INCLUSIVE ENDING (2023)"
                + " INCLUSIVE, PARTITION \"p max\" STARTING (2025) EXCLUSIVE ENDING (MAXVALUE) INCLUSIVE)",
                Db2MetaDataOperations.getPartitionClause("SALE_YEAR", partitions));
        Map<String, Object> column = new HashMap<>();
        Db2MetaDataOperations.normalizeType(column, "VARGRAPHIC", 20, 1200);
        assertEquals(20, column.get("COLUMN_SIZE"));
        column.clear();
        Db2MetaDataOperations.normalizeType(column, "CHARACTER", 4, 0);
        assertEquals("CHAR () FOR BIT DATA", column.get("TYPE_NAME"));
        assertEquals(Types.BINARY, column.get("DATA_TYPE"));
        column.clear();
        Db2MetaDataOperations.normalizeType(column, "VARCHAR", 10, 1208);
        assertTrue(column.isEmpty());
        Db2MetaDataOperations.normalizeType(column, "DECFLOAT", 8, 0);
        assertEquals("DECFLOAT(16)", column.get("TYPE_NAME"));
        assertEquals(Types.NUMERIC, column.get("DATA_TYPE"));
        Db2MetaDataOperations.normalizeType(column, "XML", 0, 0);
        assertEquals(Types.SQLXML, column.get("DATA_TYPE"));
        // Columns of a result set
        Map<String, Object> query = new HashMap<>();
        query.put("TYPE_NAME", "DECFLOAT");
        query.put("COLUMN_SIZE", 34);
        new Db2MetaDataOperations().normalizeQueryColumnInfo(query);
        assertEquals("DECFLOAT(34)", query.get("TYPE_NAME"));
        query.put("TYPE_NAME", "XML");
        new Db2MetaDataOperations().normalizeQueryColumnInfo(query);
        assertEquals(Types.SQLXML, query.get("DATA_TYPE"));
        assertTrue(Db2MetaDataOperations.class.getName().endsWith("Db2MetaDataOperations"));
    }

    private static Map<String, Object> partition(String name, String low, String lowInclusive, String high,
                                                 String highInclusive) {
        Map<String, Object> partition = new LinkedHashMap<>();
        partition.put("DATAPARTITIONNAME", name);
        partition.put("LOWVALUE", low);
        partition.put("LOWINCLUSIVE", lowInclusive);
        partition.put("HIGHVALUE", high);
        partition.put("HIGHINCLUSIVE", highInclusive);
        return partition;
    }
