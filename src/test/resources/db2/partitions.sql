-- Partitioned tables of Db2 range partitioning, a key of one column is the fixture table sales
DROP TABLE IF EXISTS sji_pt_multi;
DROP TABLE IF EXISTS sji_pt_every;
DROP TABLE IF EXISTS sji_pt_exclusive;

-- Two columns
CREATE TABLE sji_pt_multi (
    id         INTEGER  NOT NULL,
    sale_year  SMALLINT NOT NULL,
    sale_month SMALLINT NOT NULL,
    amount     DECIMAL(10,2),
    PRIMARY KEY (id, sale_year, sale_month)
) PARTITION BY RANGE (sale_year, sale_month) (
    PARTITION p_h1 STARTING (2024, 1) ENDING (2024, 6) INCLUSIVE,
    PARTITION p_h2 STARTING (2024, 7) ENDING (2024, 12) INCLUSIVE
);
INSERT INTO sji_pt_multi VALUES (1, 2024, 1, 1.5), (2, 2024, 6, 2.5), (3, 2024, 7, 3.5), (4, 2024, 12, 4.5);

-- Partitions generated by EVERY
CREATE TABLE sji_pt_every (
    id        INTEGER NOT NULL,
    sale_date DATE    NOT NULL,
    amount    DECIMAL(10,2)
) PARTITION BY RANGE (sale_date) (
    STARTING ('2024-01-01') ENDING ('2024-12-31') EVERY (3 MONTHS)
);
INSERT INTO sji_pt_every VALUES (1, '2024-01-15', 1.5), (2, '2024-05-01', 2.5), (3, '2024-08-01', 3.5),
    (4, '2024-12-31', 4.5);

-- Exclusive bounds
CREATE TABLE sji_pt_exclusive (
    id     INTEGER NOT NULL PRIMARY KEY,
    amount DECIMAL(10,2)
) PARTITION BY RANGE (id) (
    PARTITION p_low STARTING (MINVALUE) ENDING (100) EXCLUSIVE,
    PARTITION p_high STARTING (100) INCLUSIVE ENDING (MAXVALUE)
);
INSERT INTO sji_pt_exclusive VALUES (1, 1.5), (99, 2.5), (100, 3.5), (500, 4.5);
