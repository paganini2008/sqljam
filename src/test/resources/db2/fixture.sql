DROP TABLE IF EXISTS sji_emp_tag;
DROP TABLE IF EXISTS sji_emp;
DROP TABLE IF EXISTS sji_dept;
DROP TABLE IF EXISTS sji_sales;

CREATE TABLE sji_dept (
    id         INTEGER       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)  NOT NULL,
    budget     DECIMAL(12,2) DEFAULT 0,
    created_at TIMESTAMP     DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT uk_sji_dept_name UNIQUE (name)
);
COMMENT ON TABLE sji_dept IS 'Department';

CREATE TABLE sji_emp (
    id         BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id    INTEGER       REFERENCES sji_dept (id) ON DELETE CASCADE,
    name       VARCHAR(100)  NOT NULL,
    email      VARCHAR(200)  NOT NULL,
    salary     DECIMAL(10,2),
    active     BOOLEAN       DEFAULT TRUE,
    hired      DATE,
    updated_at TIMESTAMP(3),
    photo      BLOB(1M),
    profile    CLOB(1M),
    note       VARCHAR(500)  DEFAULT 'n/a'
);
COMMENT ON COLUMN sji_emp.name IS 'Employee name';
CREATE UNIQUE INDEX uk_sji_emp_email ON sji_emp (email);
CREATE INDEX idx_sji_emp_dept_name ON sji_emp (dept_id, name);

CREATE TABLE sji_emp_tag (
    emp_id   BIGINT      NOT NULL REFERENCES sji_emp (id),
    tag_name VARCHAR(50) NOT NULL,
    PRIMARY KEY (emp_id, tag_name)
);

CREATE TABLE sji_sales (
    id        INTEGER       NOT NULL,
    sale_year SMALLINT      NOT NULL,
    amount    DECIMAL(10,2),
    PRIMARY KEY (id, sale_year)
) PARTITION BY RANGE (sale_year) (
    PARTITION p2023 STARTING (MINVALUE) ENDING (2023) INCLUSIVE,
    PARTITION p2024 STARTING (2024) ENDING (2024) INCLUSIVE,
    PARTITION pmax STARTING (2025) ENDING (MAXVALUE)
);

